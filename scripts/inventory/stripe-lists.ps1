# Step-1 analysis: turns reference/live-site/_sections.tsv into each page's
# stripe list (top to bottom), using the stripe names proposed in docs/inventory.md.
# Writes docs/inventory-pages.md. Run sections.ps1 first.
# Run from the Website folder:  powershell -File scripts/inventory/stripe-lists.ps1

param([string]$Site = "reference/live-site", [string]$Out = "docs/inventory-pages.md")

# Windows PowerShell 5.1 reads this file as ANSI, so non-ASCII characters are built from codes.
$arrow = [string][char]0x2192; $times = [string][char]0xD7
$redirects = @('/woolmark', '/birthplace', '/work/moneytrees', '/work/change-drivers-season-2')

# Webflow band (tag.classes + inner classes) -> stripe name. First match wins.
# $null = page furniture that becomes part of the layout, not a stripe.
$map = @(
  @('^div\.(preloader|page-background|custom-code|w-embed|noise-overlay$)', '', $null),
  @('^div\.fl-spacing', '', $null),
  @('^div\.navbar', '', $null),
  @('^footer', '', $null),
  @('^div\.footer-background', '', 'closing-cta'),
  @('^div\.noise-overlay', 'fl-section-home-contact', 'closing-cta'),
  @('^header\.section-hero-home', '', 'hero-video'),
  @('^section\.about-hero', '', 'hero-video'),
  @('^section\.fl-who-we-are-section', '', 'statement'),
  @('^section\.fl-featured-work-section', '', 'featured-work'),
  @('^div\.background-trigger', 'fl-our-partners-section', 'partners+testimonials+news'),
  @('^div\.background-trigger', 'fl-act-sustainability', 'sustainability+values'),
  @('^div\.background-trigger', 'fl-section-act-statement', 'act-statement'),
  @('^section\.fl-act-hero-section', '', 'act-hero'),
  @('^section\.fl-section$', 'fl-active-projects', 'act-campaigns'),
  @('^section\.services-section', '', 'services'),
  @('^section\.fl-awards-section', '', 'awards'),
  @('', 'fl-core-team', 'team'),
  @('^section\.fl-life-text', '', 'heading'),
  @('^div\.section-life-with', '', 'image-marquee'),
  @('', 'fl-about-what-we-believe-split', 'big-statement'),
  @('', 'fl-earthdefender-fact', 'big-statement'),
  @('^div\.contact-parallax-wrapper', '', 'contact-hero+form+map'),
  @('^section$', 'fl-work-hero-heading', 'page-heading'),
  @('^section$', 'fl-work-layout', 'work-grid'),
  @('^section\.section', 'subtitle margin-huge', 'news-list'),
  @('^section\.section', 'categories-list', 'news-list'),
  @('^header\.section', 'category-tag', 'post-header'),
  @('^article\.section', '', 'post-body'),
  @('^section\.section', 'top-component-grid', 'related-posts'),
  @('^section\.fl-project-hero', '', 'project-hero'),
  @('^section\.fl-section-project-details', '', 'project-details'),
  @('^div\.columns', '', 'text+video'),
  @('', 'fl-project-video-medium-container', 'video(medium)'),
  @('', 'fl-split-medium-container fl-project-video', 'video(split)'),
  @('', 'fl-project-video-container', 'video(large)'),
  @('', 'responsive-iframe', 'iframe'),
  @('^div\.columns', '', 'text+video'),
  @('', 'fl-half-bg', 'text-on-image'),
  @('^section\.fl-split-small-section', '', 'text'),
  @('^section\.fl-section-gallery', '', 'gallery'),
  @('^section\.fl-quote-section', '', 'quote'),
  @('^section\.fl-campaign-section', '', 'campaign'),
  @('^section\.fl-section-numbers', '', 'stats'),
  @('^section\.fl-section-cta-big', '', 'cta-big'),
  @('^section\.fl-section-cta-small', '', 'cta-small'),
  @('^section\.fl-section-(keyvisuals|poster-haze2?|moneytrees-poster)', '', 'posters'),
  @('^section\.fl-projects-phones-section', '', 'phones'),
  @('^section\.fl-section-project-instafilter', '', 'instafilter'),
  @('^section\.fl-section-act-statement', '', 'act-statement'),
  @('^section\.section-3', 'fl-lemukih-topsection', 'cta-big'),
  @('^section\.section-4$', '', 'empty'),
  @('^section\.fl-section-next-project', '', 'next-project')
)

function StripeFor($row) {
  foreach ($m in $map) {
    if (($m[0] -eq '' -or $row.section -match $m[0]) -and ($m[1] -eq '' -or $row.inner -match [regex]::Escape($m[1]))) { return , $m[2] }
  }
  return "?($($row.section))"
}

$wf = @{}; Import-Csv -Delimiter "`t" "$Site/_wfpages.tsv" | ForEach-Object { $wf[$_.address] = $_.wfpage }
$rows = Import-Csv -Delimiter "`t" "$Site/_sections.tsv" | Where-Object { $_.address -notin $redirects }
$byPage = $rows | Group-Object address

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Stripe list per page (generated)')
$lines.Add('')
$lines.Add('Generated by `scripts/inventory/stripe-lists.ps1` from the saved copy in `reference/live-site/`. Every page except the 202 posts and 6 categories, which share one template each (one row each below). `xN` = the same stripe N times in a row. Nav, footer, preloader and spacers are left out.')
$lines.Add('')
$lines.Add('| Page | Stripes, top to bottom |')
$lines.Add('|---|---|')
$seenTemplate = @{}
foreach ($g in ($byPage | Sort-Object Name)) {
  $addr = $g.Name
  if ($addr -like '/blog-posts/*' -or $addr -like '/blog-categories/*') {
    $key = $wf[$addr]; if ($seenTemplate[$key]) { continue }; $seenTemplate[$key] = $true
    $addr = if ($addr -like '/blog-posts/*') { '/blog-posts/* (202)' } else { '/blog-categories/* (6)' }
  }
  $seq = @($g.Group | Sort-Object { [int]$_.index } | ForEach-Object { StripeFor $_ } | Where-Object { $_ })
  $parts = @(); $i = 0
  while ($i -lt $seq.Count) { $j = $i; while ($j + 1 -lt $seq.Count -and $seq[$j + 1] -eq $seq[$i]) { $j++ }; $n = $j - $i + 1; $parts += $(if ($n -gt 1) { "$($seq[$i]) $times$n" } else { $seq[$i] }); $i = $j + 1 }
  $lines.Add("| ``$addr`` | $($parts -join " $arrow ") |")
}
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
$lines | Set-Content -Encoding utf8 $Out

# Every stripe use with its Webflow classes, for finding what each stripe varies (step 3).
$rows | ForEach-Object { $s = StripeFor $_; if ($s) { $_ | Select-Object address, index, @{n = 'stripe'; e = { $s } }, section, inner, combos, slides, images, linksout, linksin, videos, iframes, text } } |
  Export-Csv -NoTypeInformation -Delimiter "`t" -Encoding utf8 "$Site/_stripes.tsv"
"wrote $Out"
