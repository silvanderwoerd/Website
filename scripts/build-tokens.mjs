// Turns design/tokens.json + design/text-styles.json into src/design/tokens.css:
// CSS variables, one class per text style (.ts-<name>), the fluid unit per
// range, and Tailwind's theme (pointing at the variables and nothing else).
// Runs before `dev` and `build`, and after every Inspector save to a design file.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// "3.5625u" → calc(3.5625 * var(--u)); anything else is used as written.
export function cssValue(v) {
  const m = /^(-?[\d.]+)u$/.exec(String(v));
  return m ? `calc(${m[1]} * var(--u))` : String(v);
}

const entries = (obj) => Object.entries(obj).filter(([k]) => !k.startsWith("$"));

// Media query per range, in the order Webflow writes them.
export function rangeQueries(bp) {
  return {
    desktopL: `(min-width: ${bp.desktopL.min}px)`,
    desktopXL: `(min-width: ${bp.desktopXL.min}px)`,
    desktopXXL: `(min-width: ${bp.desktopXXL.min}px)`,
    tablet: `(max-width: ${bp.tablet.max}px)`,
    phoneLandscape: `(max-width: ${bp.phoneLandscape.max}px)`,
    phone: `(max-width: ${bp.phone.max}px)`,
  };
}

export function buildTokens() {
  const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));
  const styles = JSON.parse(readFileSync(join(root, "design/text-styles.json"), "utf8"));
  const queries = rangeQueries(tokens.breakpoint);
  const out = [];

  out.push("/* Generated by scripts/build-tokens.mjs from design/tokens.json and design/text-styles.json. Do not edit. */");

  // Variables
  const vars = [`  --u: ${tokens.fluid.base};`];
  for (const [k, v] of entries(tokens.color)) vars.push(`  --color-${k}: ${v};`);
  for (const [k, v] of entries(tokens.overlay)) vars.push(`  --overlay-${k}: ${v};`);
  for (const [k, v] of entries(tokens.space)) vars.push(`  --space-${k}: ${cssValue(v)};`);
  for (const [k, v] of entries(tokens.spaceFixed)) vars.push(`  --space-fixed-${k}: ${v};`);
  for (const [k, v] of entries(tokens.container)) vars.push(`  --container-${k}: ${cssValue(v)};`);
  for (const [k, v] of entries(tokens.radius)) vars.push(`  --radius-${k}: ${v};`);
  for (const [k, v] of entries(tokens.z)) vars.push(`  --z-${k}: ${v};`);
  for (const [k, v] of entries(tokens.duration)) vars.push(`  --duration-${k}: ${v};`);
  for (const [k, v] of entries(tokens.ease)) vars.push(`  --ease-${k}: ${v};`);
  vars.push(`  --font-lato: var(--font-lato-file), ${tokens.font.lato};`);
  out.push(`:root {\n${vars.join("\n")}\n}`);

  // The fluid unit grows on smaller screens (Webflow's page wrapper: 2em at ≤991, 3em at ≤767).
  for (const [range, factor] of Object.entries(tokens.fluid.multiplier)) {
    if (!queries[range]) throw new Error(`fluid multiplier: unknown range "${range}"`);
    out.push(`@media ${queries[range]} {\n  :root { --u: calc(${factor} * ${tokens.fluid.base}); }\n}`);
  }

  // Text styles: one class each, then their per-range changes. size is always
  // per range; weight and lineHeight may be too ({ base, <range>: … }).
  const perRange = {};
  const base = (v) => (typeof v === "object" ? v.base : v);
  for (const [name, s] of entries(styles)) {
    const decl = ["  font-family: var(--font-lato);"];
    if (s.weight !== undefined) decl.push(`  font-weight: ${base(s.weight)};`);
    decl.push(`  font-size: ${cssValue(s.size.base)};`);
    if (s.lineHeight !== undefined) decl.push(`  line-height: ${base(s.lineHeight)};`);
    if (s.letterSpacing !== undefined) decl.push(`  letter-spacing: ${s.letterSpacing};`);
    if (s.transform !== undefined) decl.push(`  text-transform: ${s.transform};`);
    out.push(`.ts-${name} {\n${decl.join("\n")}\n}`);
    const changes = {};
    for (const [prop, values] of [["font-size", s.size], ["font-weight", s.weight], ["line-height", s.lineHeight]]) {
      if (typeof values !== "object") continue;
      for (const [range, v] of Object.entries(values)) {
        if (range === "base") continue;
        if (!queries[range]) throw new Error(`text style ${name}: unknown range "${range}"`);
        (changes[range] ??= []).push(`${prop}: ${prop === "font-size" ? cssValue(v) : v};`);
      }
    }
    for (const [range, list] of Object.entries(changes)) (perRange[range] ??= []).push(`  .ts-${name} { ${list.join(" ")} }`);
  }
  for (const range of Object.keys(queries)) {
    if (perRange[range]) out.push(`@media ${queries[range]} {\n${perRange[range].join("\n")}\n}`);
  }

  // Tailwind: forget its defaults, know only our tokens.
  const theme = ["  --*: initial;"];
  for (const [k] of entries(tokens.color)) theme.push(`  --color-${k}: var(--color-${k});`);
  for (const [k] of entries(tokens.overlay)) theme.push(`  --color-overlay-${k}: var(--overlay-${k});`);
  for (const [k] of entries(tokens.space)) theme.push(`  --spacing-${k}: var(--space-${k});`);
  for (const [k] of entries(tokens.spaceFixed)) theme.push(`  --spacing-fixed-${k}: var(--space-fixed-${k});`);
  for (const [k] of entries(tokens.container)) theme.push(`  --container-${k}: var(--container-${k});`);
  for (const [k] of entries(tokens.radius)) theme.push(`  --radius-${k}: var(--radius-${k});`);
  theme.push("  --font-lato: var(--font-lato);");
  // Tailwind needs literal widths for breakpoints; max-tablet: etc. give Webflow's max-width ranges.
  theme.push(`  --breakpoint-phone: ${tokens.breakpoint.phone.max + 1}px;`);
  theme.push(`  --breakpoint-phoneLandscape: ${tokens.breakpoint.phoneLandscape.max + 1}px;`);
  theme.push(`  --breakpoint-tablet: ${tokens.breakpoint.tablet.max + 1}px;`);
  theme.push(`  --breakpoint-desktopL: ${tokens.breakpoint.desktopL.min}px;`);
  theme.push(`  --breakpoint-desktopXL: ${tokens.breakpoint.desktopXL.min}px;`);
  theme.push(`  --breakpoint-desktopXXL: ${tokens.breakpoint.desktopXXL.min}px;`);
  out.push(`@theme inline {\n${theme.join("\n")}\n}`);

  const file = join(root, "src/design/tokens.css");
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, out.join("\n\n") + "\n");
  return file;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log(`tokens → ${buildTokens()}`);
}
